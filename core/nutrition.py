TABLE = {ingredient_key(name): values for name, values in PER_100G.items()}

MIN_KNOWN_SHARE = 0.7  # меньше: расчёт был бы гаданием
MAX_PLAUSIBLE_KCAL = 2500  # на порцию; больше: в рецепте не указано настоящее число порций


@dataclass
class Nutrition:
    calories: float
    protein_g: float
    fat_g: float
    carbs_g: float


def estimate(lines: list[RecipeLine], servings: int) -> Nutrition | None:
    """КБЖУ на порцию. None, если известна слишком малая доля состава."""
    total = known = 0.0
    sums = [0.0, 0.0, 0.0, 0.0]
    for line in lines:
        if line.quantity is None:
            continue
        grams = to_grams(line.quantity, line.unit, line.name)
        total += grams
        values = TABLE.get(ingredient_key(line.name))
        if values:
            known += grams
            for index, value in enumerate(values):
                sums[index] += value * grams / 100
    if total == 0 or known / total < MIN_KNOWN_SHARE:
        return None
    per_serving = [round(value / servings, 1) for value in sums]
    if per_serving[0] > MAX_PLAUSIBLE_KCAL or per_serving[0] == 0:
        return None
    return Nutrition(*per_serving)
